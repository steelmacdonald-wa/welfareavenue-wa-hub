-- 4. helper functions
create or replace function public.wa_email() returns text
language sql stable security definer set search_path to '' as $$
  select lower(coalesce(auth.jwt() ->> 'email', ''))
$$;

create or replace function public.my_emails() returns text[]
language sql stable security definer set search_path = '' as $$
  select array_remove(array_agg(distinct e), null) from (
    select public.wa_email() as e
    union select regexp_replace(split_part(public.wa_email(), '@', 1), '\.', '', 'g') || '@' || split_part(public.wa_email(), '@', 2)
    union select lower(a) from public.hub_directory d, unnest(coalesce(d.aliases, '{}'::text[])) a where lower(d.email) = public.wa_email()
    union select lower(d.email) from public.hub_directory d where public.wa_email() = any (select lower(x) from unnest(coalesce(d.aliases, '{}'::text[])) x)
  ) s where coalesce(e, '') <> '' and e <> '@'
$$;

create or replace function public.mybox_me() returns text
language sql stable security definer set search_path to '' as $$
  select coalesce((select a.email from public.wa_email_aliases a
                    where public.wa_email() = any (select lower(x) from unnest(a.aliases) x) limit 1), public.wa_email())
$$;
revoke all on function public.mybox_me() from public, anon;
grant execute on function public.mybox_me() to authenticated;

create or replace function public.is_hub_admin()
returns boolean language sql stable security definer set search_path to '' as $function$
  select exists (
    select 1 from public.hub_roles
    where email = lower(coalesce(auth.jwt() ->> 'email', '')) and role = 'admin'
  )
$function$;

create or replace function public.wa_is_hr()
returns boolean language sql stable security definer set search_path to 'public' as $function$ select exists (select 1 from wa_hr_access where email = lower(coalesce(auth.jwt() ->> 'email', ''))) $function$;

create or replace function public.is_wa_staff()
returns boolean language sql stable security definer set search_path to '' as $function$
  select case
    when lower(coalesce(auth.jwt()->>'email','')) = '' then false
    when exists (select 1 from public.hub_roles r
                 where r.email = lower(coalesce(auth.jwt()->>'email','')) and r.role = 'blocked') then false
    when exists (select 1 from public.hub_roles r
                 where r.email = lower(coalesce(auth.jwt()->>'email',''))
                   and r.role in ('admin','leader','member','viewer')) then true
    else coalesce(lower(auth.jwt()->>'email') like '%@welfareavenue.com', false)
  end;
$function$;
revoke all on function public.is_wa_staff() from public, anon;

create or replace function public.wa_leads_team(p_dept text) returns boolean
language sql stable security definer set search_path to '' as $$
  select coalesce(p_dept, '') <> '' and exists (
    select 1 from public.hub_roles r
     where r.email = public.wa_email() and r.role = 'leader'
       and (r.profile = p_dept or exists (select 1 from public.team_members t where lower(t.email) = any (public.my_emails()) and t.department = p_dept and coalesce(t.active, true))));
$$;

create or replace function public.wa_in_team(p_dept text) returns boolean
language sql stable security definer set search_path to '' as $$
  select coalesce(p_dept, '') <> '' and (
    exists (select 1 from public.team_members t where lower(t.email) = any (public.my_emails()) and t.department = p_dept and coalesce(t.active, true))
    or exists (select 1 from public.hub_roles r where r.email = public.wa_email() and r.profile = p_dept and r.role <> 'blocked'));
$$;

