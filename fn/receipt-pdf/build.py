#!/usr/bin/env python3
"""Join the receipt drawing (render.js, shared with the local check), the embedded fonts (fonts.js, generated here from the
TTF subsets in fonts/) and the server (serve.ts) into index.ts:  python3 fn/receipt-pdf/build.py"""
import base64, os
D = os.path.dirname(os.path.abspath(__file__))
head = """// Welfare Avenue: receipt-pdf (v2, 30/09/26 Toronto, wave185; v1 28/09/26, wave158b)
// Draws CRA donation receipts as PDFs (pdf-lib) in the Welfare Avenue brand (the green band with the cream lockup, Barlow
// Condensed headings, Space Grotesk text, the gold star doodle), in English or French. Built from render.js (the drawing,
// also run by the local check), fonts.js (the three brand fonts as base64, subset to Latin) and serve.ts by build.py: edit
// those, then rebuild this file.
// Actions (a staff JWT: the database checks the caller and the functions below run as them; or x-wa-secret, the Hub's own
// automation after an online gift, which reads through the service role):
//   sample {gift_id, lang?}  -> a sample for one gift from crm_receipt_sample: marked SAMPLE, never numbered, kept or sent (pdf_b64)
//   check {store?, return?, lang?} -> the build's check that the drawing works (x-wa-secret; a made-up receipt, nothing read or kept)
//   render {receipt_id}      -> the official copy of an issued receipt (admins, or the automation; crm_receipt_doc), drawn once
//                               into the private bucket receipts (<tax year>/<serial>.pdf) with its checksum (crm_receipt_pdf_set);
//                               a cancelled receipt gets its copy marked CANCELLED beside it (<serial>-cancelled.pdf). Returns the path.
// The signature is the image an admin uploaded to receipts/settings/signature.png; the lockup and the doodle come from the brand
// folder of content-images. A name the fonts cannot print (outside Latin) stops an official copy (issue that one by hand); a sample
// shows ? instead. The receipt's language follows the donor (the donation page's language, or the contact's).
// @ts-nocheck
import { createClient } from 'jsr:@supabase/supabase-js@2';
import * as PDFLib from 'npm:pdf-lib@1.17.1';
import fontkit from 'npm:@pdf-lib/fontkit@1.1.1';

"""
fonts = ['/* The brand fonts the receipt embeds (wave185): Barlow Condensed Medium for headings, Space Grotesk Regular and Bold for everything else,',
         '   from Google Fonts (OFL), subset to Latin, Latin-1 and Latin Extended-A (the glyphs a Canadian name or address needs) and stored as base64.',
         '   Generated by build.py from the TTF subsets in fonts/. */']
for name, fn in [('RECEIPT_FONT_HEAD', 'BarlowCondensed-500.ttf'), ('RECEIPT_FONT_BODY', 'SpaceGrotesk-400.ttf'), ('RECEIPT_FONT_BOLD', 'SpaceGrotesk-700.ttf')]:
    with open(os.path.join(D, 'fonts', fn), 'rb') as f:
        fonts.append("var %s = '%s';" % (name, base64.b64encode(f.read()).decode()))
fonts_js = '\n'.join(fonts) + '\n'
open(os.path.join(D, 'fonts.js'), 'w', encoding='utf8').write(fonts_js)
render = open(os.path.join(D, 'render.js'), encoding='utf8').read()
serve = open(os.path.join(D, 'serve.ts'), encoding='utf8').read()
out = head + render + fonts_js + serve
open(os.path.join(D, 'index.ts'), 'w', encoding='utf8').write(out)
print('index.ts', len(out), 'chars')
