-- A Toronto event is a volunteer_events row with kind 'meal' and location 'Toronto'. Every Montreal automation (the
-- confirmation, sign-up, reminder, check-in, itinerary and survey queues, the SOP steps, self sign-up, Assign) filters
-- kind = 'service', so nothing here changes a Montreal function and nothing automatic reaches a Toronto volunteer.
-- Everything below is additive: one table, two functions, the new page in the access profiles.

/* ---------- 1. who the meals of a Toronto event go to (one row per organization) ---------- */
create table if not exists public.volunteer_event_recipients (
  id bigint generated by default as identity primary key,
  event_id bigint not null references public.volunteer_events(id) on delete cascade,
  partner_id bigint references public.wa_partners(id) on delete set null,
  name text not null check (length(btrim(name)) between 1 and 160),
  meals int check (meals is null or meals between 0 and 2000),
  meals_delivered int check (meals_delivered is null or meals_delivered between 0 and 2000),
  dietary jsonb not null default '{}'::jsonb,
  drop_off text,
  address text,
  contact_name text,
  contact_email text,
  contact_phone text,
  private boolean not null default false,
  note text,
  sort int not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  updated_by text
);
create index if not exists volunteer_event_recipients_event on public.volunteer_event_recipients(event_id, sort);
alter table public.volunteer_event_recipients enable row level security;
drop policy if exists volunteer_event_recipients_staff on public.volunteer_event_recipients;
create policy volunteer_event_recipients_staff on public.volunteer_event_recipients for all to authenticated
  using (public.is_wa_staff()) with check (public.is_wa_staff());
grant select, insert, update, delete on public.volunteer_event_recipients to authenticated;
comment on table public.volunteer_event_recipients is 'wave274: who the meals of a Toronto event (volunteer_events kind meal) go to, one row per organization: name (or wa_partners), meals asked for, meals_delivered (Wrap up), dietary {halal, nut_free, vegetarian: n, vegan: n, other: text}, drop_off (a time or a window, as said), contact, private (supported but not to be named publicly, as for the TDPM in 08/26). Staff read and write.';

create or replace function public.wa274_recipients_touch() returns trigger
language plpgsql set search_path = '' as $$
begin
  new.updated_at := now();
  new.updated_by := coalesce(lower(auth.jwt() ->> 'email'), new.updated_by);
  return new;
end $$;
drop trigger if exists trg_wa274_recipients_touch on public.volunteer_event_recipients;
create trigger trg_wa274_recipients_touch before insert or update on public.volunteer_event_recipients
  for each row execute function public.wa274_recipients_touch();

/* ---------- 2. putting a CRM contact on a Toronto crew ---------- */
-- Most Toronto people came from Keela as CRM contacts without a volunteer record (43 of 44 on 05/11/26). A roster row needs
-- one (event_roster.person_id is volunteer_profiles.id), so this gives the contact a record when it has none, the one-record
-- way of wave176 (crm_contacts.volunteer_id), then adds the row. It leaves the contact's tags alone, so no tag automation
-- (crm_auto_on_tags) starts from it.
create or replace function public.wa274_crew_add(p_event bigint, p_contact bigint, p_role text) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare v_ev record; c record; v_vid bigint; v_row bigint; v_who text; v_sort int;
  v_roles constant text[] := array['team_leader', 'cook', 'server', 'driver', 'photographer', 'videographer'];
begin
  if not public.is_wa_staff() then raise exception 'Staff only'; end if;
  v_who := coalesce(lower(auth.jwt() ->> 'email'), 'staff');
  if p_role is null or not (p_role = any(v_roles)) then raise exception 'Not a Toronto crew role: %', coalesce(p_role, 'none'); end if;
  select id, code, status into v_ev from public.volunteer_events where id = p_event and kind = 'meal';
  if v_ev.id is null then raise exception 'No such Toronto event.'; end if;
  if v_ev.status in ('cancelled', 'completed') then raise exception 'This event is %.', v_ev.status; end if;
  select id, full_name, primary_email, emails, phones, volunteer_id, kinds, merged_into into c from public.crm_contacts where id = p_contact;
  if c.id is null then raise exception 'No such contact.'; end if;
  if c.merged_into is not null then raise exception 'This contact was merged into %.', c.merged_into; end if;
  v_vid := c.volunteer_id;
  if v_vid is null then
    insert into public.volunteer_profiles (roles, needs_review, joined_note)
    values (array[p_role], false, 'Toronto, added to ' || coalesce(v_ev.code, 'an event') || ' by ' || v_who)
    returning id into v_vid;
    update public.crm_contacts
       set volunteer_id = v_vid,
           kinds = case when 'volunteer' = any(coalesce(kinds, '{}'::text[])) then kinds else array_append(coalesce(kinds, '{}'::text[]), 'volunteer') end
     where id = c.id;
  end if;
  select id into v_row from public.event_roster where event_id = p_event and person_id = v_vid limit 1;
  if v_row is not null then
    return jsonb_build_object('ok', true, 'roster_id', v_row, 'person_id', v_vid, 'already', true);
  end if;
  select coalesce(max(sort), 0) + 1 into v_sort from public.event_roster where event_id = p_event;
  insert into public.event_roster (event_id, person_id, person_name, role, status, sort, detail)
  values (p_event, v_vid, c.full_name, p_role, 'TBD', v_sort,
          jsonb_build_object('source', 'toronto', 'contact_id', c.id, 'added_by', v_who,
                             'email', coalesce(c.primary_email, c.emails[1]), 'phone', c.phones[1]))
  returning id into v_row;
  insert into public.change_log (entity_type, entity_id, field, old_value, new_value, changed_by)
  values ('event_roster', v_row::text, 'added', null, coalesce(c.full_name, '') || ' as ' || p_role || ' on ' || coalesce(v_ev.code, p_event::text), v_who);
  return jsonb_build_object('ok', true, 'roster_id', v_row, 'person_id', v_vid, 'already', false);
end $$;
revoke all on function public.wa274_crew_add(bigint, bigint, text) from public;
grant execute on function public.wa274_crew_add(bigint, bigint, text) to authenticated;
comment on function public.wa274_crew_add(bigint, bigint, text) is 'wave274: put a CRM contact on a Toronto event''s crew (team_leader, cook, server, driver, photographer, videographer), giving the contact a volunteer record first when it has none (crm_contacts.volunteer_id). Returns {ok, roster_id, person_id, already}. Staff only.';

/* ---------- 3. the next Toronto event code (TO-26-1, TO-26-2 ...) ---------- */
create or replace function public.wa274_next_code(p_date date) returns text
language sql stable security definer set search_path = '' as $$
  select 'TO-' || to_char(coalesce(p_date, (now() at time zone 'America/Toronto')::date), 'YY') || '-' ||
         (coalesce(max(nullif(split_part(code, '-', 3), '')::int), 0) + 1)::text
    from public.volunteer_events
   where kind = 'meal' and code ~ ('^TO-' || to_char(coalesce(p_date, (now() at time zone 'America/Toronto')::date), 'YY') || '-[0-9]+$')
     and public.is_wa_staff();
$$;
grant execute on function public.wa274_next_code(date) to authenticated;

