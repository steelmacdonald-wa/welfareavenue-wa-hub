#!/usr/bin/env python3
"""wave140: load the refined Our story, Partners, Lessons and key facts into the Hub.

Reads the refine folder (timeline_*.json, partners.json, lessons.json, facts.json, facts.md: written by the refining
pass from the mine.* views) and writes one SQL file that:
  - adds wa_history_years (a short summary per year) and wa_history.date_end_precision;
  - upserts wa_history, wa_partners and wa_lessons by key (a leader's later edit is kept: rows with updated_by set
    to someone other than wave140 are not overwritten);
  - enriches every source with the document's name, link, where it sits, and whether it is a leadership document
    (a social post's link is the post itself, found next to the quote in the quarter's text);
  - writes two articles for Ask the Hub: the key facts, and Our story's highlights by year.
The generated SQL holds quotes from internal documents, so it stays out of the repository (the migration record keeps it).

  python3 build/data/wa140_story_load.py <refine folder> <out.sql>
"""
import calendar, glob, json, os, re, sys

SRC, OUT = sys.argv[1], sys.argv[2]
def q(s):
    return 'null' if s is None else "'" + str(s).replace("'", "''") + "'"
def qj(o):
    return 'null' if o is None else "'" + json.dumps(o, ensure_ascii=False).replace("'", "''") + "'::jsonb"
def qa(lst):
    lst = [str(x).strip() for x in (lst or []) if str(x or '').strip()]
    return "'{}'::text[]" if not lst else 'array[' + ','.join(q(x) for x in lst) + ']::text[]'
def start(d):
    d = str(d or '').strip()
    if re.fullmatch(r'\d{4}-\d{2}-\d{2}', d): return d, 'day'
    if re.fullmatch(r'\d{4}-\d{2}', d): return d + '-01', 'month'
    if re.fullmatch(r'\d{4}', d): return d + '-01-01', 'year'
    m = re.match(r'(\d{4})', d)
    return (m.group(1) + '-01-01', 'year') if m else (None, None)
def end(d):
    d = str(d or '').strip()
    if not d: return None, None
    if re.fullmatch(r'\d{4}-\d{2}-\d{2}', d): return d, 'day'
    if re.fullmatch(r'\d{4}-\d{2}', d):
        y, m = int(d[:4]), int(d[5:7]); return '%s-%02d' % (d, calendar.monthrange(y, m)[1]), 'month'
    if re.fullmatch(r'\d{4}', d): return d + '-12-31', 'year'
    return None, None
def clean_numbers(n):
    if not isinstance(n, dict): return None
    out = {k: v for k, v in n.items() if v not in (None, 0, '', '0') and not (isinstance(v, (int, float)) and v == 0)}
    return out or None
def srcs(lst):
    out = []
    for s in (lst or [])[:5]:
        if isinstance(s, dict) and s.get('file_id'):
            out.append({'file_id': str(s['file_id']), 'quote': str(s.get('quote') or '')[:400]})
    return out
def nodash(t):
    return None if t is None else str(t).replace('\u2014', ', ').replace(' \u2013 ', ', ')

# a few titles the refining left inconsistent across years
TITLE_FIX = {
    '2025-09-06-first-flag-football-fundraiser': 'First Flag Football Fundraiser with the Montreal Flag Football League raises over $2,500',
    '2026-08-08-second-flag-football-tournament': 'Second Flag Football Fundraiser grows to 13 teams and $2,800',
}

sql = ['-- wave140: Our story, Partners, Lessons and key facts (generated by build/data/wa140_story_load.py)',
       'alter table public.wa_history add column if not exists date_end_precision text check (date_end_precision in (\'day\', \'month\', \'season\', \'year\'));',
       'create table if not exists public.wa_history_years (year int primary key, summary text not null, updated_by text, updated_at timestamptz not null default now());',
       'alter table public.wa_history_years enable row level security;',
       'drop policy if exists wa_history_years_read on public.wa_history_years;',
       'create policy wa_history_years_read on public.wa_history_years for select to authenticated using (public.is_wa_staff() or public.is_board_viewer() or public.is_hub_leader());',
       'drop policy if exists wa_history_years_write on public.wa_history_years;',
       'create policy wa_history_years_write on public.wa_history_years for all to authenticated using (public.is_hub_leader()) with check (public.is_hub_leader());',
       'revoke all on public.wa_history_years from anon;',
       'grant select, insert, update, delete on public.wa_history_years to authenticated;',
       "comment on table public.wa_history_years is 'Our story: two or three sentences on what each year was for Welfare Avenue, shown at the head of the year. Staff and directors read, leaders write.';"]

# sources get their document's name, link, place and whether it is a leadership document
sql.append("""create or replace function public.wa_story_sources(p jsonb)
returns jsonb
language sql
stable
security definer
set search_path to ''
as $$
  select coalesce(jsonb_agg(x.v || jsonb_build_object(
      'name', coalesce(i.name, x.v->>'file_id'),
      'url', case when i.source = 'social' then (
                select case when position(left(x.v->>'quote', 50) in t.text) > 0
                            then substring(substring(t.text from position(left(x.v->>'quote', 50) in t.text)) from '\\[(https?://[^\\]\\s]+)\\]') end
                  from public.drive_text t where t.file_id = i.file_id)
             else i.web_url end,
      'where', case i.source when 'canva' then 'Canva' when 'social' then 'Social posts' when 'my_drive' then 'My Drive' when 'shared_with_me' then 'Shared with me' else coalesce(i.drive_name, 'Drive') end,
      'lead', (i.drive_name in ('Board of Directors', 'Management', 'Human Resources', 'Accounting', 'Steel & James') or i.source in ('my_drive', 'shared_with_me')
               or coalesce(i.sensitivity, '') in ('board', 'leadership', 'hr'))
    ) order by x.o), '[]'::jsonb)
  from jsonb_array_elements(coalesce(p, '[]'::jsonb)) with ordinality x(v, o)
  left join public.drive_inventory i on i.file_id = x.v->>'file_id';
$$;""")
sql.append('revoke all on function public.wa_story_sources(jsonb) from public, anon, authenticated;')
sql.append("comment on function public.wa_story_sources(jsonb) is 'Adds each source''s document name, link (a social post''s own link when the quote is found in its quarter), place and a lead flag (board, management, HR, finance or Steel''s own drive) to a sources array. Used when the refined story is loaded. Access: service role only.';")

years, entries = [], []
for f in sorted(glob.glob(os.path.join(SRC, 'timeline_*.json'))):
    d = json.load(open(f, encoding='utf8'))
    years += d.get('years', [])
    entries += d.get('entries', [])
for y in years:
    sql.append("insert into public.wa_history_years (year, summary, updated_by, updated_at) values (%d, %s, 'wave140', now()) on conflict (year) do update set summary = excluded.summary, updated_at = now() where public.wa_history_years.updated_by = 'wave140';"
               % (int(y['year']), q(nodash(y['summary']))))
for e in entries:
    ds, dp = start(e.get('date'))
    if not ds: continue
    de, dep = end(e.get('date_end'))
    title = TITLE_FIX.get(e['key'], e['title'])
    sql.append("insert into public.wa_history (key, date_start, date_precision, date_end, date_end_precision, title, summary, kind, city, partners, numbers, highlight, visibility, confidence, sources, status, created_by, updated_by, updated_at)\n"
               "values (%s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, public.wa_story_sources(%s), 'published', 'wave140', 'wave140', now())\n"
               "on conflict (key) do update set date_start = excluded.date_start, date_precision = excluded.date_precision, date_end = excluded.date_end, date_end_precision = excluded.date_end_precision, title = excluded.title, summary = excluded.summary, kind = excluded.kind, city = excluded.city, partners = excluded.partners, numbers = excluded.numbers, highlight = excluded.highlight, visibility = excluded.visibility, confidence = excluded.confidence, sources = excluded.sources, updated_at = now()\n"
               "  where public.wa_history.updated_by = 'wave140';"
               % (q(e['key']), q(ds), q(dp), q(de), q(dep), q(nodash(title)), q(nodash(e.get('summary'))), q(e['kind']), q(e.get('city')), qa(e.get('partners')),
                  qj(clean_numbers(e.get('numbers'))), 'true' if e.get('highlight') else 'false', q(e.get('visibility') or 'everyone'),
                  'null' if e.get('confidence') is None else str(float(e['confidence'])), qj(srcs(e.get('sources')))))

partners = json.load(open(os.path.join(SRC, 'partners.json'), encoding='utf8'))
for p in partners:
    sql.append("insert into public.wa_partners (key, name, aka, kind, city, relationship, status, first_year, last_year, summary, contact_role, visibility, sources, notes, created_by, updated_by, updated_at)\n"
               "values (%s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, public.wa_story_sources(%s), %s, 'wave140', 'wave140', now())\n"
               "on conflict (key) do update set name = excluded.name, aka = excluded.aka, kind = excluded.kind, city = excluded.city, relationship = excluded.relationship, status = excluded.status, first_year = excluded.first_year, last_year = excluded.last_year, summary = excluded.summary, contact_role = excluded.contact_role, visibility = excluded.visibility, sources = excluded.sources, notes = excluded.notes, updated_at = now()\n"
               "  where public.wa_partners.updated_by = 'wave140';"
               % (q(p['key']), q(nodash(p['name'])), qa(p.get('aka')), q(p.get('kind')), q(p.get('city')), q(p['relationship']), q(p['status']),
                  'null' if not p.get('first_year') else str(int(p['first_year'])), 'null' if not p.get('last_year') else str(int(p['last_year'])),
                  q(nodash(p.get('summary'))), q(p.get('contact_role')), q(p.get('visibility') or 'everyone'), qj(srcs(p.get('sources'))), q(nodash(p.get('note')))))

lessons = json.load(open(os.path.join(SRC, 'lessons.json'), encoding='utf8'))
for l in lessons:
    sql.append("insert into public.wa_lessons (key, lesson, context, area, topic, years, visibility, sources, status, created_by, updated_by, updated_at)\n"
               "values (%s, %s, %s, %s, %s, %s, %s, public.wa_story_sources(%s), 'published', 'wave140', 'wave140', now())\n"
               "on conflict (key) do update set lesson = excluded.lesson, context = excluded.context, area = excluded.area, topic = excluded.topic, years = excluded.years, visibility = excluded.visibility, sources = excluded.sources, updated_at = now()\n"
               "  where public.wa_lessons.updated_by = 'wave140';"
               % (q(l['key']), q(nodash(l['lesson'])), q(nodash(l.get('context'))), q(l['area']), q(l.get('topic')), q(l.get('years')), q(l.get('visibility') or 'everyone'), qj(srcs(l.get('sources')))))

# the articles for Ask the Hub
facts_md = open(os.path.join(SRC, 'facts.md'), encoding='utf8').read().strip()
sql.append("insert into public.hub_knowledge (slug, title, body, source, updated_at) values ('wa-key-facts', 'Welfare Avenue: key facts (from our documents)', %s, 'wave140 Drive mining, 26/09/26', now()) on conflict (slug) do update set title = excluded.title, body = excluded.body, source = excluded.source, updated_at = now();"
           % q(nodash(facts_md)))
by_year = {}
for e in entries:
    if e.get('visibility') == 'leadership': continue
    y = str(e.get('date') or '')[:4]
    by_year.setdefault(y, []).append(e)
lines = ['Our story: what Welfare Avenue has done since March 2020, year by year (from its own documents; the Our story page has every entry with its sources).', '']
ysum = {str(y['year']): y['summary'] for y in years}
for y in sorted(by_year):
    if not re.fullmatch(r'\d{4}', y): continue
    lines.append('## ' + y)
    if ysum.get(y): lines.append(nodash(ysum[y]))
    for e in sorted(by_year[y], key=lambda x: x['date']):
        lines.append('- ' + e['date'] + ': ' + nodash(e['title']) + '. ' + nodash(e.get('summary') or ''))
    lines.append('')
sql.append("insert into public.hub_knowledge (slug, title, body, source, updated_at) values ('wa-our-story', 'Welfare Avenue: our story since March 2020', %s, 'wave140 Drive mining, 26/09/26', now()) on conflict (slug) do update set title = excluded.title, body = excluded.body, source = excluded.source, updated_at = now();"
           % q('\n'.join(lines).strip()))
sql.append("insert into public.change_log (entity_type, entity_id, field, old_value, new_value, changed_by) values ('story', 'wave140', 'load', null, %s, 'wave140');"
           % q('%d timeline entries (%d years), %d partners, %d lessons, key facts and the story article for Ask the Hub' % (len(entries), len(years), len(partners), len(lessons))))
open(OUT, 'w', encoding='utf8').write('\n\n'.join(sql) + '\n')
print('entries', len(entries), 'years', len(years), 'partners', len(partners), 'lessons', len(lessons), 'bytes', os.path.getsize(OUT))
