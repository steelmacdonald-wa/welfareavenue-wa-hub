-- wa133_org (26/09/26): the org chart gets reporting lines and empty positions.
-- Steel: "I want the org chart to be more interactive where we can choose direct reports and move things around
-- as executives. Executives should also be able to visualize empty positions."
-- One seat per person (org_positions); a seat with no person is an empty position. reports_to null means the seat
-- reports to the executive directors (a team head). Everyone on staff reads the chart; only admins and people on the
-- Executive profile change it, and only through the functions below (each move is in the audit trail).

create table if not exists public.org_positions (
  id bigint generated by default as identity primary key,
  member_id bigint references public.team_members(id) on delete set null,
  title text not null default '',
  department text,
  reports_to bigint references public.org_positions(id) on delete set null,
  kind text not null default 'staff' check (kind in ('exec', 'staff')),
  status text not null default 'filled' check (status in ('filled', 'open', 'hiring', 'on_hold')),
  note text,
  sort int not null default 100,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  updated_by text
);
create unique index if not exists org_positions_member_uq on public.org_positions (member_id) where member_id is not null;
create index if not exists org_positions_reports_idx on public.org_positions (reports_to);
alter table public.org_positions enable row level security;
drop policy if exists org_positions_read on public.org_positions;
create policy org_positions_read on public.org_positions for select to authenticated using (public.is_wa_staff());
revoke insert, update, delete on public.org_positions from anon, authenticated;
grant select on public.org_positions to authenticated;

-- who may change the chart: admins and the Executive profile
create or replace function public.wa_org_editor()
returns boolean
language sql
stable
security definer
set search_path to ''
as $$
  select public.is_hub_admin() or exists (select 1 from public.hub_roles r where r.email = public.wa_email() and r.profile = 'executive' and r.role <> 'blocked');
$$;

-- is p_node inside p_root's part of the chart (p_root itself included)
create or replace function public.org_is_under(p_node bigint, p_root bigint)
returns boolean
language sql
stable
security definer
set search_path to ''
as $$
  with recursive up(id, depth) as (
    select p.id, 0 from public.org_positions p where p.id = p_node
    union all
    select p.reports_to, up.depth + 1 from public.org_positions p join up on p.id = up.id where p.reports_to is not null and up.depth < 50
  ) select exists (select 1 from up where id = p_root);
$$;

-- how a seat reads in the audit trail
create or replace function public.org_label(p_id bigint)
returns text
language sql
stable
security definer
set search_path to ''
as $$
  select case when p_id is null then 'the executive directors'
    else coalesce((select coalesce(m.name, 'open position') || ' (' || nullif(p.title, '') || ')' from public.org_positions p left join public.team_members m on m.id = p.member_id where p.id = p_id),
                  (select coalesce(m.name, 'open position') from public.org_positions p left join public.team_members m on m.id = p.member_id where p.id = p_id), 'a seat') end;
$$;

-- move a seat (and everyone under it) to report to another seat; null = the executive directors
create or replace function public.org_move(p_id bigint, p_reports_to bigint, p_department text default null)
returns jsonb
language plpgsql
security definer
set search_path to ''
as $$
declare p public.org_positions%rowtype; v_by text := public.wa_actor_name();
begin
  if not public.wa_org_editor() then raise exception 'only executives and admins can change the chart'; end if;
  select * into p from public.org_positions where id = p_id;
  if not found then raise exception 'that seat is not on the chart'; end if;
  if p.kind = 'exec' then raise exception 'the executive directors stay at the top'; end if;
  if p_reports_to is not null then
    if not exists (select 1 from public.org_positions where id = p_reports_to) then raise exception 'that seat is not on the chart'; end if;
    if public.org_is_under(p_reports_to, p_id) then raise exception 'someone cannot report to a person who reports to them'; end if;
  end if;
  update public.org_positions set reports_to = p_reports_to,
      department = case when member_id is null and p_department is not null then p_department else department end,
      updated_at = now(), updated_by = v_by
    where id = p_id;
  insert into public.change_log (entity_type, entity_id, field, old_value, new_value, changed_by)
  values ('org_position', p_id::text, 'reports to', public.org_label(p.reports_to), public.org_label(p_id) || ' now reports to ' || public.org_label(p_reports_to), v_by);
  return jsonb_build_object('id', p_id, 'reports_to', p_reports_to, 'was', p.reports_to);
end;
$$;

-- choose a seat's direct reports: the ones picked report to it; the ones left out move up to its own manager
create or replace function public.org_set_reports(p_id bigint, p_reports bigint[])
returns jsonb
language plpgsql
security definer
set search_path to ''
as $$
declare p public.org_positions%rowtype; v_by text := public.wa_actor_name(); v_in int := 0; v_out int := 0; r record;
begin
  if not public.wa_org_editor() then raise exception 'only executives and admins can change the chart'; end if;
  select * into p from public.org_positions where id = p_id;
  if not found then raise exception 'that seat is not on the chart'; end if;
  p_reports := coalesce(p_reports, array[]::bigint[]);
  for r in select id from public.org_positions where id = any(p_reports) and coalesce(reports_to, -1) <> p_id loop
    if r.id = p_id or public.org_is_under(p_id, r.id) then raise exception 'someone cannot report to a person who reports to them'; end if;
    if (select kind from public.org_positions where id = r.id) = 'exec' then raise exception 'the executive directors stay at the top'; end if;
    update public.org_positions set reports_to = p_id, updated_at = now(), updated_by = v_by where id = r.id;
    v_in := v_in + 1;
  end loop;
  update public.org_positions set reports_to = p.reports_to, updated_at = now(), updated_by = v_by
    where reports_to = p_id and not (id = any(p_reports));
  get diagnostics v_out = row_count;
  insert into public.change_log (entity_type, entity_id, field, old_value, new_value, changed_by)
  values ('org_position', p_id::text, 'direct reports', null,
    public.org_label(p_id) || ': ' || coalesce((select string_agg(coalesce(m.name, 'open position'), ', ' order by m.name) from public.org_positions x left join public.team_members m on m.id = x.member_id where x.reports_to = p_id), 'no one'), v_by);
  return jsonb_build_object('added', v_in, 'moved_up', v_out);
end;
$$;

-- an empty position under a seat (null = reporting to the executive directors)
create or replace function public.org_add_opening(p_reports_to bigint, p_title text, p_department text, p_status text default 'open', p_note text default null)
returns jsonb
language plpgsql
security definer
set search_path to ''
as $$
declare v_id bigint; v_by text := public.wa_actor_name(); v_title text := left(trim(coalesce(p_title, '')), 120);
begin
  if not public.wa_org_editor() then raise exception 'only executives and admins can change the chart'; end if;
  if v_title = '' then raise exception 'give the position a title'; end if;
  if p_reports_to is not null and not exists (select 1 from public.org_positions where id = p_reports_to) then raise exception 'that seat is not on the chart'; end if;
  insert into public.org_positions (member_id, title, department, reports_to, kind, status, note, sort, updated_by)
  values (null, v_title, nullif(p_department, ''), p_reports_to, 'staff', case when p_status in ('open', 'hiring', 'on_hold') then p_status else 'open' end, left(nullif(trim(coalesce(p_note, '')), ''), 300), 500, v_by)
  returning id into v_id;
  insert into public.change_log (entity_type, entity_id, field, old_value, new_value, changed_by)
  values ('org_position', v_id::text, 'open position', null, v_title || ', reporting to ' || public.org_label(p_reports_to), v_by);
  return jsonb_build_object('id', v_id);
end;
$$;

-- change a seat's title (a filled seat's title is the person's role), and an empty seat's team, status and note
create or replace function public.org_update(p_id bigint, p_title text, p_status text default null, p_note text default null, p_department text default null)
returns jsonb
language plpgsql
security definer
set search_path to ''
as $$
declare p public.org_positions%rowtype; v_by text := public.wa_actor_name(); v_title text := left(trim(coalesce(p_title, '')), 120);
begin
  if not public.wa_org_editor() then raise exception 'only executives and admins can change the chart'; end if;
  select * into p from public.org_positions where id = p_id;
  if not found then raise exception 'that seat is not on the chart'; end if;
  if v_title = '' then raise exception 'give the position a title'; end if;
  update public.org_positions set title = v_title,
      status = case when member_id is not null then 'filled' when p_status in ('open', 'hiring', 'on_hold') then p_status else status end,
      note = case when member_id is null then left(nullif(trim(coalesce(p_note, '')), ''), 300) else note end,
      department = case when member_id is null and nullif(p_department, '') is not null then p_department else department end,
      updated_at = now(), updated_by = v_by
    where id = p_id;
  if p.member_id is not null and v_title <> coalesce(p.title, '') then
    update public.team_members set role = v_title where id = p.member_id;
  end if;
  insert into public.change_log (entity_type, entity_id, field, old_value, new_value, changed_by)
  values ('org_position', p_id::text, 'position', p.title, v_title || case when p.member_id is null then ' (' || coalesce(p_status, p.status) || ')' else '' end, v_by);
  return jsonb_build_object('id', p_id);
end;
$$;

-- put someone in an empty position; the seat they leave stays on the chart as an empty position
create or replace function public.org_fill(p_id bigint, p_member_id bigint)
returns jsonb
language plpgsql
security definer
set search_path to ''
as $$
declare p public.org_positions%rowtype; v_by text := public.wa_actor_name(); v_old bigint; v_name text;
begin
  if not public.wa_org_editor() then raise exception 'only executives and admins can change the chart'; end if;
  select * into p from public.org_positions where id = p_id;
  if not found then raise exception 'that seat is not on the chart'; end if;
  if p.member_id is not null then raise exception 'that position is already filled'; end if;
  select name into v_name from public.team_members where id = p_member_id and active is not false;
  if v_name is null then raise exception 'that person is not on the roster'; end if;
  select id into v_old from public.org_positions where member_id = p_member_id;
  if v_old is not null then
    update public.org_positions set member_id = null, status = 'open', note = 'Was ' || v_name || '''s seat', updated_at = now(), updated_by = v_by where id = v_old;
  end if;
  update public.org_positions set member_id = p_member_id, status = 'filled', note = null, updated_at = now(), updated_by = v_by where id = p_id;
  if coalesce(p.title, '') <> '' then update public.team_members set role = p.title where id = p_member_id; end if;
  insert into public.change_log (entity_type, entity_id, field, old_value, new_value, changed_by)
  values ('org_position', p_id::text, 'filled', p.title, v_name || ' takes the position' || case when v_old is not null then ' (their old seat is now an open position)' else '' end, v_by);
  return jsonb_build_object('id', p_id, 'left_open', v_old);
end;
$$;

-- put someone who is not on the chart yet under a seat (null = reporting to the executive directors)
create or replace function public.org_place(p_member_id bigint, p_reports_to bigint)
returns jsonb
language plpgsql
security definer
set search_path to ''
as $$
declare v_id bigint; v_by text := public.wa_actor_name(); m public.team_members%rowtype;
begin
  if not public.wa_org_editor() then raise exception 'only executives and admins can change the chart'; end if;
  select * into m from public.team_members where id = p_member_id and active is not false;
  if not found then raise exception 'that person is not on the roster'; end if;
  if exists (select 1 from public.org_positions where member_id = p_member_id) then raise exception 'that person is already on the chart'; end if;
  if p_reports_to is not null and not exists (select 1 from public.org_positions where id = p_reports_to) then raise exception 'that seat is not on the chart'; end if;
  insert into public.org_positions (member_id, title, department, reports_to, kind, status, sort, updated_by)
  values (p_member_id, coalesce(nullif(m.role, ''), 'Team member'), m.department, p_reports_to, 'staff', 'filled', 100, v_by)
  returning id into v_id;
  insert into public.change_log (entity_type, entity_id, field, old_value, new_value, changed_by)
  values ('org_position', v_id::text, 'placed', null, m.name || ' reports to ' || public.org_label(p_reports_to), v_by);
  return jsonb_build_object('id', v_id);
end;
$$;

-- take someone off their seat (they stay on the roster; the seat stays as an empty position)
create or replace function public.org_vacate(p_id bigint)
returns jsonb
language plpgsql
security definer
set search_path to ''
as $$
declare p public.org_positions%rowtype; v_by text := public.wa_actor_name(); v_name text;
begin
  if not public.wa_org_editor() then raise exception 'only executives and admins can change the chart'; end if;
  select * into p from public.org_positions where id = p_id;
  if not found or p.member_id is null then raise exception 'that seat is already empty'; end if;
  if p.kind = 'exec' then raise exception 'the executive directors stay at the top'; end if;
  select name into v_name from public.team_members where id = p.member_id;
  update public.org_positions set member_id = null, status = 'open', note = 'Was ' || coalesce(v_name, 'someone') || '''s seat', updated_at = now(), updated_by = v_by where id = p_id;
  insert into public.change_log (entity_type, entity_id, field, old_value, new_value, changed_by)
  values ('org_position', p_id::text, 'left the seat', coalesce(v_name, 'someone'), p.title || ' is now an open position', v_by);
  return jsonb_build_object('id', p_id);
end;
$$;

-- remove an empty position; whoever reported to it moves up to its manager
create or replace function public.org_remove(p_id bigint)
returns jsonb
language plpgsql
security definer
set search_path to ''
as $$
declare p public.org_positions%rowtype; v_by text := public.wa_actor_name(); v_n int;
begin
  if not public.wa_org_editor() then raise exception 'only executives and admins can change the chart'; end if;
  select * into p from public.org_positions where id = p_id;
  if not found then raise exception 'that seat is not on the chart'; end if;
  if p.member_id is not null then raise exception 'take the person off the seat first'; end if;
  update public.org_positions set reports_to = p.reports_to, updated_at = now(), updated_by = v_by where reports_to = p_id;
  get diagnostics v_n = row_count;
  delete from public.org_positions where id = p_id;
  insert into public.change_log (entity_type, entity_id, field, old_value, new_value, changed_by)
  values ('org_position', p_id::text, 'removed', p.title, 'open position removed' || case when v_n > 0 then ', ' || v_n || ' moved up to ' || public.org_label(p.reports_to) else '' end, v_by);
  return jsonb_build_object('moved_up', v_n);
end;
$$;

-- the roster keeps the chart in step: a new person gets a seat under their team's lead; someone who leaves leaves an empty
-- position behind; a changed role changes the seat's title
create or replace function public.wa133_roster_sync()
returns trigger
language plpgsql
security definer
set search_path to ''
as $$
declare v_head bigint;
begin
  if coalesce(new.department, '') = 'board' then return new; end if;
  if tg_op = 'INSERT' or (tg_op = 'UPDATE' and new.active is not false and old.active is false) then
    if new.active is not false and not exists (select 1 from public.org_positions where member_id = new.id) then
      select h.id into v_head from public.org_positions h
        where h.kind = 'staff' and h.reports_to is null and h.member_id is not null
          and coalesce((select m.department from public.team_members m where m.id = h.member_id), h.department) = new.department
        order by h.sort, h.id limit 1;
      insert into public.org_positions (member_id, title, department, reports_to, kind, status, sort, updated_by)
      values (new.id, coalesce(nullif(new.role, ''), 'Team member'), new.department, v_head, 'staff', 'filled', 100, 'the roster');
    end if;
  elsif tg_op = 'UPDATE' then
    if new.active is false and old.active is not false then
      update public.org_positions set member_id = null, status = 'open', note = 'Was ' || coalesce(new.name, 'someone') || '''s seat', updated_at = now(), updated_by = 'the roster'
        where member_id = new.id and kind = 'staff';
    elsif coalesce(new.role, '') <> coalesce(old.role, '') and nullif(new.role, '') is not null then
      update public.org_positions set title = new.role, updated_at = now() where member_id = new.id and title is distinct from new.role;
    end if;
  end if;
  return new;
end;
$$;
drop trigger if exists trg_wa133_roster on public.team_members;
create trigger trg_wa133_roster after insert or update of active, role, department on public.team_members
  for each row execute function public.wa133_roster_sync();

