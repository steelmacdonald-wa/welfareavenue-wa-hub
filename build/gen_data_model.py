#!/usr/bin/env python3
"""Write docs/DATA_MODEL.md from the schema comments in build/data.

The comments live in the database (COMMENT ON), where agents read them; this makes the same text readable in
the repo. wa134_comments.sql gives the areas and the order; every later migration in build/data that has
single-line `comment on ... is '...';` statements (wa134_passwords.sql, wa135_academy_names.sql, ...) is read
after it, in file name order: a later comment replaces an earlier one for the same object, a new column joins
its table, and anything else new goes under "Added after wave134". Test files (*_test.sql) are skipped.
A dropped object leaves the model through a line `-- dropped: column public.<table>.<column>` (or table, view,
function) in the migration that drops it (wave192e); a later comment brings it back.
Run after each migration that adds or changes a comment: python3 build/gen_data_model.py
"""
import glob
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, 'build', 'data')
BASE = os.path.join(DATA, 'wa134_comments.sql')
later = [f for f in sorted(glob.glob(os.path.join(DATA, '*.sql')))
         if f != BASE and not f.endswith('_test.sql') and re.search(r'^(comment on |-- dropped: )', open(f, encoding='utf-8').read(), re.M)]
pat = re.compile(r"^comment on (table|view|column|function) (public\.[^ ]+(?: ?\([^)]*\))?) is '(.*)';$")
drop_pat = re.compile(r"^-- dropped: (table|view|column|function) (public\.[^ ]+(?: ?\([^)]*\))?)\s*$")   # wave192e: a later file records a drop
order = []            # keys in first-seen order
text = {}             # key -> latest text
kind_of = {}          # key -> table | view | column | function
section_of = {}       # key -> section title
section_order = []
cur = None
for f in [BASE] + later:
    lines = open(f, encoding='utf-8').read().split('\n')
    for i, line in enumerate(lines):
        if f == BASE and line.startswith('-- ') and i > 0 and lines[i - 1].startswith('-- ----') and i + 1 < len(lines) and lines[i + 1].startswith('-- ----'):
            cur = line[3:].strip()
            if cur not in section_order:
                section_order.append(cur)
            continue
        d = drop_pat.match(line)
        if d:   # the object (and, for a table or view, its columns) leaves the model; a later comment brings it back
            dk = d.group(1) + ' ' + d.group(2).replace('public.', '')
            gone = [dk] + ([k for k in text if k.startswith('column ' + dk.split(' ', 1)[1] + '.')] if d.group(1) in ('table', 'view') else [])
            for k in gone:
                if k in text:
                    del text[k]; order.remove(k)
            continue
        m = pat.match(line)
        if not m:
            continue
        kind, name, body = m.group(1), m.group(2).replace('public.', ''), m.group(3).replace("''", "'")
        key = kind + ' ' + name
        if key not in text:
            order.append(key)
            kind_of[key] = kind
            if f == BASE:
                section_of[key] = cur or 'Other'
            elif kind == 'column' and ('table ' + name.split('.')[0]) in section_of:
                section_of[key] = section_of['table ' + name.split('.')[0]]
            else:
                section_of[key] = 'Added after wave134'
        text[key] = body
for k in order:
    if section_of[k] not in section_order:
        section_order.append(section_of[k])
sections = [(t, [(kind_of[k], k.split(' ', 1)[1], text[k]) for k in order if section_of[k] == t]) for t in section_order]
out = ['# Welfare Avenue Hub: the data model', '',
       'Generated by `build/gen_data_model.py` from the schema comments in `build/data` (`wa134_comments.sql` and every later migration that sets a comment). The comments themselves live in the database (`COMMENT ON`), so an agent reading the schema sees the same text. When a table or column changes, update its comment in the same migration and regenerate this file.', '',
       '## Conventions', '',
       '- **Team code**: one of `opsmtl`, `progdev`, `opsto`, `marketing`, `fundraising`, `hr`, `board`. `dept_meta` is the list, with each team\'s `label`, `short_label`, `sort` and `color`. No foreign key enforces the code yet.',
       '- **People**: `team_members.id` is the person key for staff and the board; `volunteer_people.id` for volunteers. Many older columns hold a display name (usually a first name) or an email instead; the comments say which.',
       '- **Done**: `dept_tasks.done` (with `closed_at`) is the truth; `dept_tasks.status` is a legacy free-text label.',
       '- **Confidentiality**: `board_only`, `confidential`, `visibility` (NULL, empty, department, leadership, private) and, for tasks and projects, `banked_at` (the bank). Edge functions use the service role and must apply these filters themselves.',
       '- **Service role**: edge functions and cron jobs; they bypass row-level security.',
       '- **Audit trail**: `change_log` (who changed what); job runs are also written there today.', '']
for title, items in sections:
    if not items:
        continue
    out.append('## ' + title)
    out.append('')
    tables = [x for x in items if x[0] in ('table', 'view')]
    cols = [x for x in items if x[0] == 'column']
    fns = [x for x in items if x[0] == 'function']
    for kind, name, text in tables:
        out.append('### `' + name + '`' + (' (view)' if kind == 'view' else ''))
        out.append('')
        out.append(text)
        mine = [c for c in cols if c[1].split('.')[0] == name]
        if mine:
            out.append('')
            for _, cname, ctext in mine:
                out.append('- `' + cname.split('.', 1)[1] + '`: ' + ctext)
        out.append('')
    orphan_cols = [c for c in cols if c[1].split('.')[0] not in [t[1] for t in tables]]
    if orphan_cols:
        for _, cname, ctext in orphan_cols:
            out.append('- `' + cname + '`: ' + ctext)
        out.append('')
    if fns:
        out.append('Functions:')
        out.append('')
        for _, fname, ftext in fns:
            out.append('- `' + fname + '`: ' + ftext)
        out.append('')
open(os.path.join(ROOT, 'docs', 'DATA_MODEL.md'), 'w', encoding='utf-8').write('\n'.join(out) + '\n')
print('docs/DATA_MODEL.md', sum(len(s[1]) for s in sections), 'comments in', len(sections), 'sections')
